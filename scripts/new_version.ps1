#==============================================================================
# scripts/new_version.ps1 - start a new dated version of a project
#
#   Convention used by this repository (see VERSIONS.md / docs/versioning.md):
#
#     <name>_<YYYYMMDD>_<NN>      NN = 01, 02, ... within the same day
#
#   * the new project lives in   proj\<name>_<YYYYMMDD>_<NN>\
#   * the sources it was created from are snapshotted to
#                                backup\<name>_<YYYYMMDD>_<NN>\
#     (same version string, so a snapshot is always paired with the version
#      whose creation it precedes)
#   * nothing is ever deleted or overwritten: every older version stays where
#     it is, and the snapshot keeps the rtl/docs/scripts of that moment too.
#
#   Usage (from the repository root):
#
#     scripts\new_version.ps1                              # from proj\dbg_20260924_01
#     scripts\new_version.ps1 -SourceDir proj\system -BaseName system_dbg
#     scripts\new_version.ps1 -WhatIfOnly                  # just show the name
#
#   Build artifacts (outflow / work_syn / work_pnr / work_dbg) are NOT copied
#   into the new version - they are re-generated by the first build.
#==============================================================================
param(
    [string] $SourceDir  = 'proj\dbg_20260924_01',
    [string] $BaseName   = '',
    [string] $Date       = (Get-Date -Format 'yyyyMMdd'),
    [string] $Root       = (Split-Path -Parent $PSScriptRoot),
    [switch] $WhatIfOnly
)

$ErrorActionPreference = 'Stop'

function Get-NextSequence {
    param([string] $RootDir, [string] $Prefix)
    $used = 0
    foreach ($dir in @((Join-Path $RootDir 'proj'), (Join-Path $RootDir 'backup'))) {
        if (Test-Path -LiteralPath $dir) {
            Get-ChildItem -LiteralPath $dir -Directory -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -like "$Prefix*" } |
                ForEach-Object {
                    if ($_.Name -match '_(\d{2})$') {
                        $n = [int]$Matches[1]
                        if ($n -gt $used) { $used = $n }
                    }
                }
        }
    }
    return $used + 1
}

$src = Join-Path $Root $SourceDir
if (-not (Test-Path -LiteralPath $src)) { throw "source project not found: $src" }

if (-not $BaseName) {
    # strip a trailing _YYYYMMDD_NN (or the plain project directory name)
    $leaf = Split-Path -Leaf (Resolve-Path -LiteralPath $src).Path
    $BaseName = $leaf -replace '_\d{8}_\d{2}$', ''
}

$prefix  = "${BaseName}_${Date}_"
$nn      = '{0:d2}' -f (Get-NextSequence -RootDir $Root -Prefix $prefix)
$version = "${BaseName}_${Date}_${nn}"

$projDst   = Join-Path $Root (Join-Path 'proj'   $version)
$backupDst = Join-Path $Root (Join-Path 'backup' $version)

Write-Host "base name    : $BaseName"
Write-Host "new version  : $version"
Write-Host "new project  : $projDst"
Write-Host "source backup: $backupDst"

if ($WhatIfOnly) { return }

if (Test-Path -LiteralPath $projDst)   { throw "already exists: $projDst" }
if (Test-Path -LiteralPath $backupDst) { throw "already exists: $backupDst" }

#------------------------------------------------------------------ 1. snapshot
New-Item -ItemType Directory -Force -Path $backupDst | Out-Null
$xd = @('-XD', (Join-Path $Root 'backup'), (Join-Path $Root 'ref'),
        (Join-Path $Root 'tmp'), (Join-Path $Root '.git'),
        'outflow', 'work_syn', 'work_pnr', 'work_dbg', '__pycache__')
& robocopy $Root $backupDst /E /NFL /NDL /NJH /NJS @xd /XF '*.vvp' | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy (snapshot) failed: $LASTEXITCODE" }
Write-Host "snapshot done"

#-------------------------------------------------------------- 2. new project
New-Item -ItemType Directory -Force -Path $projDst | Out-Null
& robocopy $src $projDst /E /NFL /NDL /NJH /NJS `
        /XD 'outflow' 'work_syn' 'work_pnr' 'work_dbg' '__pycache__' | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy (project) failed: $LASTEXITCODE" }

$oldXml  = Get-ChildItem -LiteralPath $projDst -File -Filter '*.xml' |
           Where-Object { $_.Name -notlike '*.peri.xml' } | Select-Object -First 1
if (-not $oldXml) { throw "no project .xml found in $projDst" }
$oldName = [System.IO.Path]::GetFileNameWithoutExtension($oldXml.Name)
$newName = $version

$renames = @{
    "$oldName.xml"      = "$newName.xml"
    "$oldName.sdc"      = "$newName.sdc"
    "$oldName.peri.xml" = "$newName.peri.xml"
}
foreach ($pair in $renames.GetEnumerator()) {
    $from = Join-Path $projDst $pair.Key
    if (Test-Path -LiteralPath $from) {
        Move-Item -LiteralPath $from -Destination (Join-Path $projDst $pair.Value)
    }
}

# re-point the project metadata at the new name
$xmlPath = Join-Path $projDst "$newName.xml"
$xml = Get-Content -LiteralPath $xmlPath -Raw -Encoding UTF8
$xml = $xml.Replace("name=`"$oldName`"", "name=`"$newName`"")
$xml = $xml.Replace("name=`"$oldName.sdc`"", "name=`"$newName.sdc`"")
Set-Content -LiteralPath $xmlPath -Value $xml -Encoding UTF8 -NoNewline

$periPath = Join-Path $projDst "$newName.peri.xml"
if (Test-Path -LiteralPath $periPath) {
    $peri = Get-Content -LiteralPath $periPath -Raw -Encoding UTF8
    $peri = $peri.Replace("design_db name=`"$oldName`"", "design_db name=`"$newName`"")
    Set-Content -LiteralPath $periPath -Value $peri -Encoding UTF8 -NoNewline
}

# the wizard profile references only the top module and net names, so it can be
# carried over as-is; the debug core itself is re-generated on demand.

Write-Host ""
Write-Host "created:"
Write-Host "  $projDst"
Write-Host "  $backupDst"
Write-Host ""
Write-Host "next:"
Write-Host "  1. add a row to VERSIONS.md"
Write-Host "  2. build it:  scripts\build.ps1 proj\$newName\$newName.xml"
if (Test-Path -LiteralPath (Join-Path $projDst 'dbg_core.selection.json')) {
    Write-Host "  3. if you changed the probe list, re-generate the debug core:"
    Write-Host "       scripts\build_dbg_core.ps1 -Selection proj\$newName\dbg_core.selection.json"
}
